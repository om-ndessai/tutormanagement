#!/usr/bin/env node
/**
 * The question bank's NEW checked questions since a release, as INSERT files for production.
 *
 *   node db/release-questions.mjs --since=<git ref> --out=<dir> [--per-file=12000]
 *
 * Compares db/questions/*.json now with the same files at <ref> (a `release-*` tag: what production
 * already holds) and writes the checked questions whose ids are new, as `<dir>/questions-NN.sql`, at most
 * --per-file questions to a file. INSERTs only, `ON CONFLICT (id) DO NOTHING`, no reviewer: approving is a
 * person's act in production's console, exactly like `generate-questions.mjs --production`.
 *
 * Why the files are split: one question is about five rows written in D1 (the row, its primary key and
 * three indexes), and the free plan writes 100,000 rows a day for the whole account. 12,000 questions is
 * about 60,000 rows, which leaves the day's real use room. Load one file a day.
 *
 * Read-only on the repository; it never touches a database.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCES = join(here, 'questions');
const arg = (name) => process.argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3);
const since = arg('since');
const out = arg('out');
const perFile = Number(arg('per-file') ?? 12000);
if (!since || !out || !(perFile > 0)) {
  console.error('usage: node db/release-questions.mjs --since=<git ref> --out=<dir> [--per-file=12000]');
  process.exit(1);
}

const repoRoot = execFileSync('git', ['rev-parse', '--show-toplevel'], { cwd: here, encoding: 'utf8' }).trim();
const sourcesInRepo = relative(repoRoot, SOURCES);
const git = (...args) => execFileSync('git', args, { cwd: repoRoot, encoding: 'utf8', maxBuffer: 1 << 30 });

/** Every question id in db/questions/*.json at the ref. */
const released = new Set();
const atRef = git('ls-tree', '--name-only', `${since}:${sourcesInRepo}`).split('\n').filter((f) => f.endsWith('.json'));
for (const file of atRef) {
  for (const q of JSON.parse(git('show', `${since}:${sourcesInRepo}/${file}`)).questions ?? []) released.add(q.id);
}

const sql = (value) => (value === null || value === undefined ? 'NULL' : `'${String(value).replace(/'/g, "''")}'`);
const fresh = [];
const perLevel = new Map();
for (const file of readdirSync(SOURCES).filter((f) => f.endsWith('.json')).sort()) {
  const source = JSON.parse(readFileSync(join(SOURCES, file), 'utf8'));
  for (const q of source.questions ?? []) {
    if (q.status !== 'checked' || released.has(q.id)) continue;
    perLevel.set(source.level_id, (perLevel.get(source.level_id) ?? 0) + 1);
    fresh.push(
      `INSERT INTO questions (id, topic_id, difficulty, kind, skill, stem, choices, answer, compute, solution, status, checks, source, reviewed_by, reviewed_at)
VALUES (${[
        sql(q.id), sql(q.topic_id), q.difficulty, sql(q.kind), sql(q.skill ?? null), sql(q.stem),
        sql(JSON.stringify(q.choices ?? [])), sql(q.answer), sql(q.compute ?? null), sql(q.solution), sql('checked'),
        sql(JSON.stringify(q.checks ?? { lint: [], solve: null })), sql(q.source ?? 'manual'), 'NULL', 'NULL',
      ].join(', ')})
ON CONFLICT (id) DO NOTHING;`,
    );
  }
}

if (!existsSync(out)) mkdirSync(out, { recursive: true });
const files = Math.ceil(fresh.length / perFile);
for (let i = 0; i < files; i++) {
  const name = join(out, `questions-${String(i + 1).padStart(2, '0')}.sql`);
  const part = fresh.slice(i * perFile, (i + 1) * perFile);
  writeFileSync(
    name,
    `-- GENERATED by db/release-questions.mjs --since=${since}: new CHECKED questions for production's bank,
-- file ${i + 1} of ${files} (${part.length} questions, about ${part.length * 5} rows written). Inserts only.
${part.join('\n')}
`,
  );
}
console.log(`release-questions: ${released.size} ids at ${since}; ${fresh.length} new checked questions in ${files} file(s) under ${out}.`);
for (const [level, n] of perLevel) console.log(`  ${level}: ${n}`);
