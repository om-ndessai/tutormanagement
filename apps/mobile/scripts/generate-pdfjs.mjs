// Generate pdf.js, inlined, for the assessment PDF viewer's web view (Phase 38).
//
// A reviewer reads an assessment's PDF inside the app, never as a download: the PDF carries the
// answer key and the worked solutions. pdf.js (the web's own viewer library, same version) draws it
// in a react-native-webview whose page loads nothing from anywhere. So the page carries pdf.js
// itself: `legacy/build/pdf.min.mjs` and `legacy/build/pdf.worker.min.mjs`, each as base64 -- base64 because it
// can sit in the page's inline script as it is (no `</script>`, no escaping to get wrong), and the
// page turns each back into a Blob URL: the library is imported from one, the worker runs from the
// other.
//
// The LEGACY build (2026-10-30): the modern one calls features Safari only gained after iOS 18
// (Map.prototype.getOrInsertComputed), so on an iPhone on iOS 18 the viewer drew nothing. The legacy
// build polyfills them, for about 10% more.
//
//   node scripts/generate-pdfjs.mjs          write the file
//   node scripts/generate-pdfjs.mjs --check  fail if the file is stale (run by typecheck)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
// Resolved from this app's own node_modules (a devDependency pinned to the web's version).
const require = createRequire(join(here, '..', 'package.json'));
const PDFJS = dirname(require.resolve('pdfjs-dist/package.json'));
const VERSION = JSON.parse(readFileSync(join(PDFJS, 'package.json'), 'utf8')).version;
const OUT = resolve(here, '../src/features/canvas-assessments/pdfjs.generated.ts');

const lib = readFileSync(join(PDFJS, 'legacy/build/pdf.min.mjs'));
const worker = readFileSync(join(PDFJS, 'legacy/build/pdf.worker.min.mjs'));

const file = `// Generated by scripts/generate-pdfjs.mjs from pdfjs-dist@${VERSION} (legacy/build/pdf.min.mjs and
// legacy/build/pdf.worker.min.mjs), each as base64. Never edit by hand: run \`node scripts/generate-pdfjs.mjs\`.
export const PDFJS_VERSION = '${VERSION}';

export const PDFJS_LIB_BASE64 = '${lib.toString('base64')}';

export const PDFJS_WORKER_BASE64 = '${worker.toString('base64')}';
`;

const size = `${Math.round(file.length / 1024)} KB`;
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // missing: stale
  }
  if (current !== file) {
    console.error('pdfjs.generated.ts is stale: run `node scripts/generate-pdfjs.mjs` (in apps/mobile).');
    process.exit(1);
  }
  console.log(`pdfjs: up to date (pdfjs-dist ${VERSION}, ${size})`);
} else {
  writeFileSync(OUT, file);
  console.log(`wrote ${OUT} (pdfjs-dist ${VERSION}, ${size})`);
}
