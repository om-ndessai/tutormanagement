# The welcome screen's "AimTrue" wordmark, drawn from Nunito ExtraBold itself: the outlines and the
# kerning (HarfBuzz) of the font the app's headings use, so the arrow sits exactly on the T's bar.
# The T loses its right arm, which becomes the arrow's shaft, carried on over "rue" to a head.
#
#   python3 -m venv /tmp/wm && /tmp/wm/bin/pip install fonttools uharfbuzz
#   /tmp/wm/bin/python scripts/wordmark/make-wordmark.py \
#     node_modules/@expo-google-fonts/nunito/800ExtraBold/Nunito_800ExtraBold.ttf \
#     src/features/auth/wordmark-paths.generated.ts
import sys
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import RecordingPen

path = sys.argv[1]
font = TTFont(path)
gs = font.getGlyphSet()
order = font.getGlyphOrder()
blob = hb.Blob.from_file_path(path)
hbfont = hb.Font(hb.Face(blob))
buf = hb.Buffer(); buf.add_str('AimTrue'); buf.guess_segment_properties()
hb.shape(hbfont, buf, {'kern': True, 'liga': False})

ASC = 1011  # hhea ascent: the baseline sits this far below the top
x = 0
glyphs = []
for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
    name = order[info.codepoint]
    pen = SVGPathPen(gs)
    tpen = TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, ASC - pos.y_offset))
    if name == 'T':
        # The T without its right arm: its top edge stops square over the stem, where the arrow starts.
        rec = RecordingPen(); gs[name].draw(rec)
        ops, skip = [], 0
        for op, pts in rec.value:
            if op == 'lineTo' and pts == ((571, 705),):
                ops.append(('lineTo', ((394, 705),))); skip = 2; continue
            if skip:
                skip -= 1; continue
            ops.append((op, pts))
        RecordingPen.replay(type('R', (), {'value': ops})(), tpen)
    else:
        gs[name].draw(tpen)
    bp = BoundsPen(gs); gs[name].draw(bp)
    glyphs.append({'name': name, 'x': x, 'd': pen.getCommands(), 'bounds': bp.bounds})
    x += pos.x_advance

t = next(g for g in glyphs if g['name'] == 'T')
e = glyphs[-1]
bar_top, bar_bottom = ASC - 705, ASC - 577          # the T's top bar, flipped
bar_mid = (bar_top + bar_bottom) / 2
stem_right = t['x'] + 394                            # where the stem ends and the right arm starts
e_right = e['x'] + e['bounds'][2]
arm = 150                                            # chevron arm length
half = (bar_bottom - bar_top) / 2                    # 64: half the bar's thickness
tip = e_right + 70 + arm + half                      # the head clears the e
arrow = {
    # the arm and shaft, square at the stem so it reads as the T's own bar (2 units into the stem: no seam)
    'shaft': f'M{stem_right - 2} {bar_top}H{tip - half}V{bar_bottom}H{stem_right - 2}Z',
    'head': f'M{tip - arm - half} {bar_mid - arm}L{tip - half} {bar_mid}L{tip - arm - half} {bar_mid + arm}',
    'stroke': bar_bottom - bar_top,
}
width = round(tip + 10)
aim = ''.join(g['d'] for g in glyphs[:3])
true = ''.join(g['d'] for g in glyphs[3:])
ts = f'''// GENERATED by scripts/wordmark/make-wordmark.py -- do not edit by hand.
// "AimTrue" in Nunito ExtraBold, outlines and kerning from the font itself, in font units (1000 to
// the em), the baseline at y = {ASC}. The T has no right arm: that is where the arrow starts.

/** The part of the drawing the wordmark shows: from the arrowhead's top to just under the baseline. */
export const WORDMARK_VIEWBOX = '0 150 {width} 880';
export const WORDMARK_ASPECT = {width} / 880;

/** "Aim". */
export const WORDMARK_AIM = '{aim}';

/** "True", its T without the right arm. */
export const WORDMARK_TRUE = '{true}';

/** The T's right arm, carried on over "rue" as the arrow's shaft. */
export const WORDMARK_ARROW_SHAFT = '{arrow['shaft']}';

/** The arrowhead: a stroke as thick as the T's bar, rounded. */
export const WORDMARK_ARROW_HEAD = '{arrow['head']}';
export const WORDMARK_ARROW_STROKE = {arrow['stroke']};
'''
open(sys.argv[2], 'w').write(ts)
print('wrote', sys.argv[2], 'width', width)
