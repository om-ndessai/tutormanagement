// Generate KaTeX's stylesheet, with its fonts inlined, for the question bank's web view (#54).
//
// The bank's maths is drawn by KaTeX (the same renderer as the web app) in a react-native-webview
// whose page may load nothing: its CSP is `default-src 'none'; font-src data:`. So the page carries
// KaTeX's CSS itself, and each `@font-face` keeps only its woff2, inlined as a `data:` URI. All 20
// faces are kept (~400 KB): a face left out would fall back to another font without a word.
// KaTeX's CSS carries no colour of its own (only `currentColor`), so the page's colours stay the
// theme's tokens.
//
//   node scripts/generate-katex-css.mjs          write the file
//   node scripts/generate-katex-css.mjs --check  fail if the file is stale (run by typecheck)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const KATEX = dirname(require.resolve('katex/package.json'));
const VERSION = JSON.parse(readFileSync(join(KATEX, 'package.json'), 'utf8')).version;
const OUT = resolve(here, '../src/features/question-bank/katex-css.generated.ts');

export function inlineFonts(css, readFont) {
  let faces = 0;
  const out = css.replace(/@font-face\{([^}]*)\}/g, (_, body) => {
    const woff2 = /url\((fonts\/[^)]+\.woff2)\)/.exec(body);
    if (!woff2) throw new Error(`a @font-face without a woff2: ${body}`);
    const data = readFont(woff2[1]).toString('base64');
    faces += 1;
    const rest = body.replace(/src:[^;}]*/, `src:url(data:font/woff2;base64,${data}) format("woff2")`);
    return `@font-face{${rest}}`;
  });
  if (/url\((?!data:)/.test(out)) throw new Error('a url() other than an inlined font is left');
  return { css: out, faces };
}

const source = readFileSync(join(KATEX, 'dist/katex.min.css'), 'utf8');
const { css, faces } = inlineFonts(source, (path) => readFileSync(join(KATEX, 'dist', path)));
if (faces !== 20) throw new Error(`expected KaTeX's 20 font faces, found ${faces}`);

const file = `// Generated by scripts/generate-katex-css.mjs from katex@${VERSION} (dist/katex.min.css), with each
// font's woff2 inlined. Never edit by hand: run \`node scripts/generate-katex-css.mjs\`.
export const KATEX_VERSION = '${VERSION}';

export const KATEX_CSS = ${JSON.stringify(css)};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // missing: stale
  }
  if (current !== file) {
    console.error(
      'katex-css.generated.ts is stale: run `node scripts/generate-katex-css.mjs` (in apps/mobile).',
    );
    process.exit(1);
  }
  console.log(`katex css: up to date (katex ${VERSION}, ${faces} faces)`);
} else {
  writeFileSync(OUT, file);
  console.log(`wrote ${OUT} (katex ${VERSION}, ${faces} faces, ${Math.round(file.length / 1024)} KB)`);
}
